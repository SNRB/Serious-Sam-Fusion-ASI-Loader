#!/usr/bin/env python3
"""Generate exe_expect.h: identity of Sam2017_SeriousEditor.exe (7 June 2019 build),
FNV-1a 64 hashes of the code the plugin relies on, and the original bytes of the
call sites it redirects. Usage: gen_expect.py <path-to-exe> <out.h>"""
import sys, struct

exe_path, out_path = sys.argv[1], sys.argv[2]
d = open(exe_path, 'rb').read()
e = struct.unpack_from('<I', d, 0x3c)[0]
nsec = struct.unpack_from('<H', d, e + 6)[0]
ts = struct.unpack_from('<I', d, e + 8)[0]
opt = e + 24
osz = struct.unpack_from('<H', d, e + 20)[0]
image_base = struct.unpack_from('<Q', d, opt + 24)[0]
size_of_image = struct.unpack_from('<I', d, opt + 56)[0]
checksum = struct.unpack_from('<I', d, opt + 64)[0]
secs = []
for i in range(nsec):
    o = opt + osz + 40 * i
    vsz, va, rsz, raw = struct.unpack_from('<IIII', d, o + 8)
    secs.append((va, vsz, raw, rsz))

def read(rva, n):
    for va, vsz, raw, rsz in secs:
        if va <= rva and rva + n <= va + rsz:
            return d[raw + rva - va: raw + rva - va + n]
    raise ValueError('rva %#x not in file data' % rva)

def fnv1a64(b):
    h = 0xcbf29ce484222325
    for c in b:
        h ^= c
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return h

# Call sites the plugin redirects: (rva, SITE_ name, original call target, what)
patches = [
    (0x0B6A72B, 'CORE_DECLARATIONS', 0x0B2E3E0, 'call RegisterDeclarations in the Core module initializer'),
    (0x075B0D6, 'HELP_CVAR_LIST',    0x075B430, 'call LoadCvarsHelp in the list of all console variables'),
    (0x075B281, 'HELP_COMMAND',      0x075B430, 'call LoadCvarsHelp in the "help" console command'),
    (0x075BFCD, 'HELP_LOOKUP',       0x075B430, 'call LoadCvarsHelp in the help lookup used by the console tooltip'),
    (0x0160B48, 'EDITOR_COMMANDS',   0x1611F00, 'call GetGlobalCommandHandler before the editor registers its tool commands'),
]

# (rva, length, what) - code/data the plugin depends on
regions = [
    (0x0B2E3E0, 0x12C, 'RegisterDeclarations(table): parses kind-2 records and registers them'),
    (0x0B2CC10, 0x123, 'variable declaration record parser (record layout the plugin produces)'),
    (0x075B430, 0x1DE, 'LoadCvarsHelp: clears the help records, reads Help/Cvars/ *_cvars.xml, sets the loaded flag'),
    (0x075BFB0, 0x01D, 'cvar help lookup, before its LoadCvarsHelp call'),
    (0x075BFD2, 0x085, 'cvar help lookup, after its LoadCvarsHelp call (first match, 0x58-byte records)'),
    (0x075ACF0, 0x071, 'CCvarDesc constructor'),
    (0x075AF20, 0x119, 'CCvarDesc array expand'),
    (0x0B25F30, 0x061, 'CString::operator=(const char *)'),
    (0x1611F00, 0x005, 'GetGlobalCommandHandler: jmp'),
    (0x16740D0, 0x008, 'GetGlobalCommandHandler: mov rax,[CommandHandler.Global] ; ret'),
    (0x1610600, 0x0B9, 'RegisterCommand(handler, id, tooltip, execute, update, extra)'),
    (0x1610430, 0x13C, 'RegisterShortcut(handler, command id, shortcut id, key, event, extra)'),
    (0x0B1FFD0, 0x048, 'console message of type CMT_INFO'),
    (0x0B572E0, 0x15B, 'cvar saving: only cvars with the saved flag (0x4) are written to the INI'),
    (0x0648693, 0x007, 'reader of hud_bShowGeometryInfo (0x142AB9874)'),
    (0x0BD8BA6, 0x006, 'reader of res_bSaveInTextFormat (0x141EFB2D8)'),
    (0x1576FB2, 0x006, 'reader of res_bSaveInTextFormat (0x141EFB2D8)'),
    (0x054A570, 0x007, 'reader of scr_bUnsecureScripting (0x142A72FD8)'),
    (0x0E8D721, 0x006, 'reader of prj_bUnlockAutoShotgunScope (0x143279248)'),
    (0x139D2BF, 0x007, 'reader of men_bMenuFrame (0x143289A70)'),
    (0x0F79886, 0x007, 'reader of prj_bAllowLevelChangeInEditor (0x143278EAC)'),
    (0x0543A9F, 0x007, 'reader of fxd_bShowDebug (0x142AC5C50)'),
    (0x0B5A5AE, 0x007, 'reader of fil_bReportFileOpen (0x1431DE4C8)'),
    (0x0B6B5C7, 0x007, 'reader of md_bReportReadStats (0x1431DE960)'),
]
# the 16 bytes before and after every redirected call must be the original too
for rva, name, target, what in patches:
    regions.append((rva - 16, 16, 'code before the redirected call at 0x%X' % (0x140000000 + rva)))
    regions.append((rva + 5, 16, 'code after the redirected call at 0x%X' % (0x140000000 + rva)))

# no verified byte may be one the plugin changes (or a second copy would not recognize the first)
changed = set()
for rva, name, target, what in patches:
    changed.update(range(rva + 1, rva + 5))
changed.add(0x0B730F3)                          # the byte the toggle command flips
for rva, n, what in regions:
    assert not changed.intersection(range(rva, rva + n)), 'region %#x+%#x overlaps a changed byte' % (rva, n)

lines = []
lines.append('/* Generated by gen_expect.py from %s - do not edit. */' % exe_path.split('/')[-1])
lines.append('#define EXE_TIMEDATESTAMP 0x%08Xu' % ts)
lines.append('#define EXE_SIZEOFIMAGE   0x%08Xu' % size_of_image)
lines.append('#define EXE_CHECKSUM      0x%08Xu' % checksum)
lines.append('#define EXE_IMAGEBASE     0x%XULL' % image_base)
lines.append('')
lines.append('static const struct VerifyRegion { unsigned int rva, len; unsigned long long hash; } g_verify[] = {')
for rva, n, what in regions:
    lines.append('    { 0x%07X, 0x%03X, 0x%016XULL }, /* %s */' % (rva, n, fnv1a64(read(rva, n)), what))
lines.append('};')
lines.append('')
lines.append('#define NUM_SITES %d' % len(patches))
for i, (rva, name, target, what) in enumerate(patches):
    lines.append('#define SITE_%-18s %d' % (name, i))
lines.append('static const struct CallSite { unsigned int rva; unsigned char orig[5]; } g_sites[] = {')
for rva, name, target, what in patches:
    b = read(rva, 5)
    assert b[0] == 0xE8, 'site %#x is not a call' % rva
    assert rva + 5 + struct.unpack('<i', b[1:])[0] == target, 'site %#x does not call %#x' % (rva, target)
    lines.append('    { 0x%07X, { %s } }, /* %s */' % (rva, ', '.join('0x%02X' % x for x in b), what))
lines.append('};')
open(out_path, 'w').write('\n'.join(lines) + '\n')
print('\n'.join(lines))
